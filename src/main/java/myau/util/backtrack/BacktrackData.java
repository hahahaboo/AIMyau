package myau.util.backtrack;

public class BacktrackData {

    public double x;
    public double y;
    public double z;
    public long time;

    public BacktrackData(double x, double y, double z, long time) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.time = time;
    }

}
